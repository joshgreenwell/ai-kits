def coverage(adapter, state, detail=None, **counts):
    row = {"adapter": adapter, "state": state, "detail_code": detail, "stores_discovered": 0, "files": 0, "bytes_read": 0,
           "records_emitted": 0, "malformed": 0, "rejected_by_server": 0, "duration_ms": 1,
           "cursor_state": "complete" if state in ("ok", "partial") else "unknown", "probe_requests": 0,
           "parser_version": "2.0.0+v1.1.0" if adapter.endswith("_execution") or adapter.endswith("_browser") else "0"}
    row.update(counts)
    return row


