def load_collect():
    spec = importlib.util.spec_from_file_location("collect", COLLECT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_v1(provider: str, roots: list[Path], quota_inbox: Path | None) -> dict:
    c = load_collect()
    with tempfile.TemporaryDirectory(prefix="parity-") as temp:
        source_id = str(uuid.uuid4())
        config = {"source_id": source_id, "account_id": ACCOUNTS[provider], "provider": provider, "mode": "local",
                  "url": "https://localhost", "key": "SYNTHETIC", "roots": [str(r) for r in roots]}
        if quota_inbox is not None:
            config["quota_inbox"] = str(quota_inbox)
        config_path = Path(temp) / "connection.json"
        config_path.write_text(json.dumps(config))
        result = subprocess.run([sys.executable, str(COLLECT), "--config", str(config_path), "--since", SINCE, "--dry-run"],
                                capture_output=True, text=True, check=True)
        output = json.loads(result.stdout.strip().splitlines()[-1])
        db = c.open_state(Path(temp) / f"{source_id}.sqlite3")
        buckets = list(c.bucket_rows(db))
        events = [dict(row) for row in db.execute(
            "SELECT id, session, hour, model, input_tokens, cached_tokens, cache_write_tokens, output_tokens FROM events ORDER BY id")]
        quotas = sorted((json.loads(row["payload"]) for row in db.execute("SELECT payload FROM quotas")),
                        key=lambda q: (q["window_key"], q["observed_at"]))
        files = db.execute("SELECT count(*) FROM files").fetchone()[0]
        db.close()
    cov = output["coverage"]
    return {
        "coverage": {k: cov[k] for k in ("files", "bytes_read", "malformed_lines", "unavailable_roots")},
        "collector_version": cov["collector_version"],
        "dry_run": {"buckets": output["buckets"], "quotas": output["quotas"]},
        "checkpointed_files": files,
        "buckets": buckets,
        "bucket_digests": [{"key": c.digest([b["session_hash"], b["hour"], b["model"]]), "hash": c.digest(b)} for b in buckets],
        "events": events,
        "quotas": quotas,
    }


