def check() -> int:
    problems = []
    current = expected()
    committed = json.loads((PARITY / "expected.json").read_bytes()) if (PARITY / "expected.json").exists() else None
    if committed != current:
        problems.append("parity/expected.json is not what collect.py produces; run `python3 scripts/fixtures.py expected`")
    if json.loads((CORPUS / "MANIFEST.json").read_bytes()) != manifest():
        problems.append("MANIFEST.json is stale; run `python3 scripts/fixtures.py generate`")
    for name, envelope in valid_envelopes().items():
        path = WIRE / "valid" / f"{name}.json"
        if not path.exists() or json.loads(path.read_bytes()) != envelope:
            problems.append(f"wire/valid/{name}.json is stale")
    for name, (reason, expressible, envelope) in invalid_envelopes().items():
        path = WIRE / "invalid" / f"{name}.json"
        if not path.exists() or json.loads(path.read_bytes()).get("envelope") != envelope:
            problems.append(f"wire/invalid/{name}.json is stale")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    if command == "generate":
        generate()
        print(f"wrote corpus under {CORPUS}")
        return 0
    if command == "expected":
        dump(PARITY / "expected.json", expected())
        dump(CORPUS / "MANIFEST.json", manifest())
        print(f"wrote {PARITY / 'expected.json'}")
        return 0
    if command == "check":
        return check()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
